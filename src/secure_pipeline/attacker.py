class AttackerHarness:
    """
    Black-box Attacker Simulation Client.

    Probes the target RAG pipeline and classifies existence/leakage solely
    from observable side-channels.
    """

    def __init__(self, actor: str = "bob", session_id: str = "attacker_session") -> None:
        self.actor = actor
        self.session_id = session_id

    def probe(
        self,
        pipeline: SecureRAGPipeline,
        probe_def: ProbeDefinition,
        step_label: str = "",
    ) -> tuple[PipelineQueryResult, AttackerInference]:
        """
        Execute a probe query and generate black-box existence inference.
        """
        result = pipeline.query(
            actor=self.actor,
            session_id=self.session_id,
            query_text=probe_def.query_text,
            step_label=step_label or f"probe_{probe_def.strategy}_{probe_def.target_doc_id}",
            strategy=probe_def.strategy,
        )

        inference = self._infer_existence(probe_def, result)
        return result, inference

    def _infer_existence(
        self,
        probe_def: ProbeDefinition,
        result: PipelineQueryResult,
    ) -> AttackerInference:
        """
        Heuristic existence inference classifier operating strictly on black-box signals.
        """
        inferred = False
        confidence = 0.0
        reasons = []

        resp_lower = result.response.lower()

        # Signal 1: Content leakage in response
        if any(term in resp_lower for term in ["67.3%", "nightingale", "nextomazumab", "8,367,000", "privata", "cvf-2025-001", "helios", "4.2 bps"]):
            inferred = True
            confidence = max(confidence, 0.99)
            reasons.append("Direct restricted content returned in response text")

        # Signal 2: Cache hit
        if result.cache_hit:
            inferred = True
            confidence = max(confidence, 0.95)
            reasons.append("Immediate semantic cache hit detected")

        # Signal 3: Distinct refusal asymmetry (e.g. 'access_denied' vs 'not_found')
        if result.refusal_type == "access_denied":
            inferred = True
            confidence = max(confidence, 0.90)
            reasons.append("Observable refusal type explicitly signaled access denial")

        # Signal 4: Raw similarity score elevation (in baseline mode)
        if result.raw_similarity_score > 0.65:
            inferred = True
            confidence = max(confidence, 0.85)
            reasons.append(f"High similarity score ({result.raw_similarity_score:.3f}) observed")
        elif result.raw_similarity_score > 0.40 and result.refusal_type != "standardized_refusal":
            inferred = True
            confidence = max(confidence, 0.65)
            reasons.append(f"Elevated similarity score ({result.raw_similarity_score:.3f}) observed")

        # Signal 5: Timing anomaly in baseline mode
        if probe_def.strategy == "timing_only" and result.raw_latency_ms < 50.0 and not result.cache_hit:
            inferred = True
            confidence = max(confidence, 0.60)
            reasons.append(f"Fast refusal latency ({result.raw_latency_ms:.1f}ms) indicated early-stage filter")

        if not inferred:
            confidence = 0.10
            reasons.append("No distinguishing side-channel or content signals detected")

        return AttackerInference(
            target_doc_id=probe_def.target_doc_id,
            target_topic=probe_def.target_topic,
            strategy=probe_def.strategy,
            query_text=probe_def.query_text,
            inferred_exists=inferred,
            confidence=confidence,
            reasoning="; ".join(reasons),
            observed_response=result.response,
            observed_latency_ms=result.effective_latency_ms,
            observed_similarity=result.normalized_similarity_score if result.similarity_band != "None" else result.raw_similarity_score,
            observed_refusal=result.refusal_type,
        )

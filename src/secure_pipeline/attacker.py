@dataclass
class AttackerInference:
    """Black-box binary existence / content inference generated by the attacker."""
    target_doc_id: str
    target_topic: str
    strategy: str
    query_text: str
    inferred_exists: bool          # Binary prediction: does restricted doc exist?
    confidence: float              # Confidence score [0.0, 1.0]
    reasoning: str
    observed_response: str
    observed_latency_ms: float
    observed_similarity: float
    observed_refusal: Optional[str]



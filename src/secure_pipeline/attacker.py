"""
attacker.py -- Attacker Simulation Harness & Black-Box Probing Client (§3.8, §5.4).

Implements 4 Black-Box Probing Strategies:
1. Direct Query Strategy: Direct questions probing for restricted entities/documents.
2. Paraphrase Drift Strategy: Semantically identical queries with lexical drift.
3. Comparative Probing Strategy: Comparative prompts contrasting public vs restricted topics.
4. Timing-Only Strategy: Inference based exclusively on latency distributions.

The harness evaluates observable outputs (content, scores, latency, refusal type)
WITHOUT access to ground truth, producing existence and content inferences for scoring.
"""

